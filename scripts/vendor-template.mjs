#!/usr/bin/env node
// Vendors the Org Context Spec starter template into src/template.ts.
// One source of truth: the spec repo's template/ folder. Run at release time:
//   node scripts/vendor-template.mjs [path-to-spec-repo]
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specRepo = process.argv[2] ?? join(here, "..", "..", "org-context-spec");

const files = {};
function vendor(root, prefix) {
  (function walk(dir) {
    for (const name of readdirSync(dir).sort()) {
      const abs = join(dir, name);
      if (statSync(abs).isDirectory()) walk(abs);
      else if (name.endsWith(".md")) {
        files[prefix + relative(root, abs).replaceAll("\\", "/")] = readFileSync(abs, "utf8");
      }
    }
  })(root);
}
// Core template keys mirror repo paths; packs keep their method-packs/ prefix.
vendor(join(specRepo, "template", "org-context"), "");
vendor(join(specRepo, "template", "method-packs"), "method-packs/");

const out =
  `// GENERATED by scripts/vendor-template.mjs — do not edit by hand.\n` +
  `// Source: the Org Context Spec starter template\n` +
  `// (https://github.com/org-spec/org-context-spec, template/org-context/).\n` +
  `// Vendored ${new Date().toISOString().slice(0, 10)}.\n\n` +
  `export const TEMPLATE: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;

writeFileSync(join(here, "..", "src", "template.ts"), out);
console.log(`Vendored ${Object.keys(files).length} template files into src/template.ts`);
